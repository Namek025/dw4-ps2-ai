#!/usr/bin/env python3
"""Write the Alchemy meta boilerplate of a unit with the macros in include/ig_meta.h.

Every registered class has a run of small functions (create / getClassMeta / register /
thunk / retrieveVTable / instantiate / enum getters). This recognizes them in the splat
asm of a unit's INCLUDE_ASM functions, replaces each with its IG_META_* macro and writes
the prototypes they need in a generated block of the unit. With --check it then compiles
the unit with MWCC, compares every generated function against the rom (tools/fcmp.py)
and puts back the INCLUDE_ASM of any that differ, until all generated ones match.

Usage: python3 tools/meta_src.py src/UNIT.cpp... [--check] [--dry-run]
  WIBO / MWCC env vars override the compiler paths (e.g. in the Docker container).
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import configure  # noqa: E402  (compiler flags per unit)

BEGIN = "// BEGIN generated by tools/meta_src.py"
END = "// END generated by tools/meta_src.py"
INCLUDE_ASM = re.compile(r'^INCLUDE_ASM\("([^"]+)", (\w+)\);$', re.M)
MACRO = re.compile(r"^(?:#pragma exceptions off\n)?(IG_META_\w+)\((\w+)[,)].*\n"
r"(?:(?:IG_FIELD|IG_SET|IG_CALL|IG_OVERRIDES)\w*.*\n)*(?:#pragma exceptions reset\n)?", re.M)


def tailcall(macro):
    """MWCC only emits a tail call (`j`) with C++ exceptions off for that function."""
    return f"#pragma exceptions off\n{macro}\n#pragma exceptions reset"
INSN = re.compile(r"/\* \w+ [0-9A-F]{8} [0-9A-F]{8} \*/\s+(\S+)\s*(.*)")
SYM = re.compile(r"%(?:hi|lo)\((\w+)\)")
HEADER_SYMS = {"D_00586DC8", "D_00587040"}  # declared by ig_meta.h

REGNAMES = {"zero": 0, "at": 1, "v0": 2, "v1": 3, "sp": 29, "fp": 30, "ra": 31, "gp": 28}
REGNAMES.update({f"a{i}": 4 + i for i in range(4)})
REGNAMES.update({f"t{i}": 8 + i for i in range(8)})
REGNAMES.update({f"s{i}": 16 + i for i in range(8)})
REGNAMES.update({"t8": 24, "t9": 25})


def reg(r):
    r = r.strip().lstrip("$")
    return int(r) if r.isdigit() else REGNAMES.get(r, -1)


def load_asm(unit, fn):
    for d in ("nonmatchings", "matchings"):
        p = ROOT / "asm" / d / unit / f"{fn}.s"
        if p.exists():
            break
    else:
        return None
    ins = []
    inside = False
    frame = 0
    for line in p.read_text().splitlines():
        if line.startswith("glabel"):
            inside = True
            continue
        if line.startswith("endlabel"):
            break
        m = INSN.search(line)
        if inside and m:
            op, args = m.group(1), [a.strip() for a in m.group(2).split(",")] if m.group(2) else []
            ins.append((op, args))
    if ins and ins[0][0] == "addiu" and reg(ins[0][1][0]) == 29:
        frame = -int(ins[0][1][2], 0)
    return {"ins": ins, "ops": [op for op, _ in ins], "frame": frame,
            "calls": [a[0] for op, a in ins if op == "jal"],
            "syms": [s for _, a in ins for x in a for s in SYM.findall(x)]}


def lw_sym(f):
    for op, a in f["ins"]:
        if op == "lw" and len(a) == 2:
            m = SYM.search(a[1])
            if m:
                return m.group(1)
    return None


def track_call(f, upto_call):
    """Argument registers and stack stores right before the n-th jal."""
    regs, stack, n = {}, {}, 0
    for op, a in f["ins"]:
        if op == "jal":
            if n == upto_call:
                break
            n += 1
            continue
        if op == "lui" and len(a) == 2:
            m = SYM.search(a[1])
            regs[reg(a[0])] = m.group(1) if m else None
        elif op == "addiu" and len(a) == 3:
            m = SYM.search(a[2])
            if m:
                regs[reg(a[0])] = m.group(1)
            elif reg(a[1]) == 0:
                regs[reg(a[0])] = int(a[2], 0)
        elif op == "daddu" and len(a) == 3 and reg(a[2]) == 0:
            regs[reg(a[0])] = 0 if reg(a[1]) == 0 else regs.get(reg(a[1]))
        elif op in ("sd", "sw") and len(a) == 2:
            m = re.match(r"(-?0x[0-9A-Fa-f]+|\d+)\(\$(?:sp|29)\)", a[1])
            if m:
                stack[int(m.group(1), 0)] = 0 if reg(a[0]) == 0 else regs.get(reg(a[0]))
    # The delay slot of the call runs before it.
    return regs, stack


def delay_slot_fix(f):
    """Swap each jal with its delay slot so a linear walk sees the slot first."""
    ins = list(f["ins"])
    i = 0
    while i < len(ins) - 1:
        if ins[i][0] == "jal":
            ins[i], ins[i + 1] = ins[i + 1], ins[i]
            i += 1
        i += 1
    g = dict(f)
    g["ins"] = ins
    return g


OPS = {
    "create": "addiu lui sd lw bnez lui jal lw jal daddu lui sw lui ld lw jr addiu".split(),
    "get_class_meta": "addiu lui sd lw beqz nop lw andi sltu bnez nop nop jal nop lui ld lw jr addiu".split(),
    "thunk": "addiu sd jal nop ld jr addiu".split(),
    "ark": "addiu lui sd jal addiu ld jr addiu".split(),
    "vtable": "addiu sd jal addiu lui lui lw addiu sw ld lw addu lw jr addiu".split(),
    "instantiate": "addiu sd sq jal daddu lui lw jal daddu ld lq jr addiu".split(),
    "enum": "addiu lui sd lw bnez lui lui lui addiu addiu addiu jal addiu lui sw nop lui ld lw jr addiu".split(),
    "getter": "lui jr lw".split(),
}


def struct_sizes():
    sizes = {}
    size = None
    for line in (ROOT / "include/meta.h").read_text().splitlines():
        m = re.match(r"/\* size (0x[0-9A-Fa-f]+) \*/", line)
        if m:
            size = int(m.group(1), 16)
            continue
        m = re.match(r"struct (\w+)\b.*\{", line)
        if m and size is not None:
            sizes[m.group(1)] = size
        size = None
    return sizes


def recognize(fn, f, vtable_class, sizes, vtable_fns=frozenset()):
    """(macro text, {symbol: kind}) or None. Kinds: meta, enum, void, getmeta, vtable, inst, data.
    Ndmw/Bec are built -O4,p; Alchemy -O4,s (one nop less, tail calls as `j`)."""
    ops, calls = f["ops"], f["calls"]
    tail = [a[0] for op, a in f["ins"] if op == "j"]
    if ops == OPS["getter"]:
        m = lw_sym(f)
        return f"IG_META_GETTER({fn}, {m})", {m: "meta", fn: "getmeta"}
    if calls == ["func_002F88E0", "func_002BE4F0"] and len(ops) in (17, 18) and ops[:4] == OPS["create"][:4]:
        m = lw_sym(f)
        return f"IG_META_CREATE({fn}, {m})", {m: "meta", fn: "getmeta"}
    if len(ops) in (18, 19) and ops[:5] == OPS["get_class_meta"][:5] and len(calls) == 1 and \
            any(op == "andi" and a[2] == "0x4" for op, a in f["ins"]):
        m = lw_sym(f)
        return f"IG_META_GET_CLASS_META({fn}, {m}, {calls[0]})", {m: "meta", calls[0]: "void", fn: "getmeta"}
    if (ops == OPS["thunk"] and len(calls) == 1) or (ops == ["j", "nop"] and tail):
        target = calls[0] if calls else tail[0]
        wrap = tailcall if tail else (lambda m: m)
        if fn in vtable_fns:  # passed as retrieveVTable: forwards to the class's own
            return wrap(f"IG_META_VTABLE_THUNK({fn}, {target})"), {target: "vtable", fn: "vtable"}
        return wrap(f"IG_META_THUNK({fn}, {target})"), {target: "getmeta", fn: "getmeta"}
    if (ops == OPS["ark"] and calls == ["func_002FE940"]) or \
            (ops == ["lui", "j", "addiu"] and tail == ["func_002FE940"]):
        r = [s for s in f["syms"]][-1]
        wrap = tailcall if tail else (lambda m: m)
        return wrap(f"IG_META_ARK_REGISTER({fn}, {r})"), {r: "void", fn: "void"}
    if ops == "addiu sd jal nop lui jal addiu ld jr addiu".split() and len(calls) == 2 and \
            fn in vtable_fns and len(set(f["syms"])) == 1:
        # metaRegister's 9th argument in Alchemy: a setup call, then one with a function
        arg = f["syms"][0]
        return (f"IG_META_SETUP({fn}, {calls[0]}, {calls[1]}, {arg})",
                {calls[0]: "void", calls[1]: "setfn", arg: "void", fn: "vtable"})
    if ops == OPS["vtable"] and calls == ["func_002FEF20"] and fn in vtable_class:
        t = vtable_class[fn]
        vt = [s for s in f["syms"] if s != "D_00586DC8"]
        if t in sizes and len(set(vt)) == 1 and f["frame"] == (0x10 + sizes[t] + 15) // 16 * 16:
            return f"IG_META_VTABLE({fn}, {t}, {vt[0]})", {vt[0]: "data", fn: "vtable"}
    if ops == OPS["instantiate"] and len(calls) == 2 and calls[1] == "func_002FDA40":
        m = lw_sym(f)
        return f"IG_META_INSTANTIATE({fn}, {m}, {calls[0]})", {m: "meta", calls[0]: "void", fn: "inst"}
    if ops == OPS["enum"] and calls == ["func_002FBC70"]:
        g = delay_slot_fix(f)
        regs, _ = track_call(g, 0)
        st = lw_sym(f)
        args = [regs.get(4), regs.get(5), regs.get(6), regs.get(7)]
        if all(isinstance(x, str) for x in args[:3]) and isinstance(args[3], int):
            return (f"IG_META_ENUM({fn}, {st}, {args[0]}, {args[1]}, {args[2]}, {args[3]})",
                    {st: "enum", args[0]: "data", args[1]: "data", args[2]: "data", fn: "enumget"})
    r = recognize_fields(fn, f)
    if r:
        return r
    if len(calls) == 2 and calls[1] == "metaRegister" and \
            set(ops) <= {"addiu", "sd", "jal", "nop", "lui", "daddu", "ld", "jr"}:
        g = delay_slot_fix(f)
        regs, stack = track_call(g, 1)
        a = [regs.get(i) for i in (4, 5, 6, 7, 8, 9, 10, 11)] + [stack.get(0), stack.get(8), stack.get(0x10)]
        if not isinstance(a[0], int) or not isinstance(a[1], str) or not isinstance(a[6], int):
            return None
        kinds = {calls[0]: "void", a[1]: "meta", fn: "void"}
        roles = [None, None, "void", "getmeta", "getmeta", "data", None, "vtable", "void", "vtable", "data"]
        out = []
        for i, (v, role) in enumerate(zip(a, roles)):
            if i in (0, 1):
                continue
            if v is None:
                return None
            if v == 0:
                out.append("0" if i == 6 else "NULL")
            elif isinstance(v, int):
                out.append(hex(v))
            else:
                out.append(v)
                kinds.setdefault(v, role)
        return (f"IG_META_REGISTER({fn}, {calls[0]}, {a[0]}, {a[1]}, " + ", ".join(out) + ")", kinds)
    return None


FIELD_OPS = {"addiu", "lui", "sd", "sq", "lw", "jal", "daddu", "sw", "sb", "sh", "ld", "lq", "jr", "nop",
             "jalr", "bnez", "dsll32", "dsrl32"}
# Calls that take the field being fixed and one value.
FIELD_SETTERS = {"func_0030AA10", "func_002EA4B0", "func_002D3890", "func_002EBC00"}
STORE_TYPES = {"sw": "s32", "sh": "s16", "sb": "u8"}


def recognize_fields(fn, f):
    """X_registerFields: IG_META_FIELDS, then per field IG_FIELD(k) / IG_FIELD_OVERRIDE(name)
    with IG_SET / IG_CALL lines, then IG_FIELDS_END. A small symbolic run over the asm."""
    calls = f["calls"]
    only_overrides = calls[:1] == ["func_002FDF20"] and "metaSetFieldNames" not in calls
    if not only_overrides and (len(calls) < 2 or calls[:2] != ["func_002FE470", "metaSetFieldTypes"] or
                               "metaSetFieldNames" not in calls[-2:]) or not set(f["ops"]) <= FIELD_OPS:
        return None
    meta = lw_sym(f)
    kinds = {meta: "meta", fn: "void"}
    regs = {}          # reg -> value: (kind, payload)
    lines = []
    field = None       # value of the field being fixed: ("field", n) / ("copy", n)
    nfield = 0
    types = count = names = a2 = offs = None
    post = None
    skipping = False   # the copy's reference release after an override

    def close():
        nonlocal field
        if field is not None:
            lines.append("IG_FIELD_OVERRIDE_END" if field[0] == "copy" else "IG_FIELD_END")
        field = None

    def value(r):
        v = regs.get(r) if r else ("int", 0)
        if v is None:
            raise ValueError
        if v[0] == "int":
            return v[1], None
        if v[0] == "sym":
            kinds.setdefault(v[1], "data")
            return v[1], "void*"
        if v[0] == "ret":
            kinds.setdefault(v[1], "getmeta")
            return f"{v[1]}()", "void*"
        raise ValueError

    ins = list(f["ins"])
    i = 0
    while i < len(ins) - 1:  # delay slots run before their call
        if ins[i][0] in ("jal", "jalr"):
            ins[i], ins[i + 1] = ins[i + 1], ins[i]
            i += 1
        i += 1
    try:
        for op, a in ins:
            if skipping:
                if op == "jal" and a[0] == "func_002FF820":
                    skipping = False
                continue
            r = [reg(x) for x in a[:1]]
            if op in ("sd", "sq", "ld", "lq", "jr", "nop", "bnez", "dsll32", "dsrl32"):
                continue
            if op == "lui":
                m = SYM.search(a[1])
                regs[r[0]] = ("hi", m.group(1)) if m else None
            elif op == "addiu" and reg(a[0]) == 29:
                continue
            elif op == "addiu":
                m = SYM.search(a[2])
                src = regs.get(reg(a[1]))
                if m:
                    regs[r[0]] = ("sym", m.group(1))
                elif reg(a[1]) == 0:
                    regs[r[0]] = ("int", int(a[2], 0))
                elif src and src[0] == "base":
                    regs[r[0]] = ("base", src[1] + int(a[2], 0))
                else:
                    regs[r[0]] = None
            elif op == "daddu" and reg(a[2]) == 0:
                regs[r[0]] = ("int", 0) if reg(a[1]) == 0 else regs.get(reg(a[1]))
            elif op == "lw":
                m = SYM.search(a[1])
                base_reg = reg(re.search(r"\((\$\w+)\)", a[1]).group(1))
                off = a[1].split("(")[0]
                src = regs.get(base_reg)
                if m:
                    regs[r[0]] = ("meta",) if m.group(1) == meta else None
                elif src == ("meta",) and off == "0x28":
                    regs[r[0]] = ("list",)
                elif src and src[0] == "orig" and off == "0x0":
                    regs[r[0]] = ("vptr",)
                elif src == ("vptr",) and off == "0x54":
                    regs[r[0]] = ("vfn",)
                else:
                    regs[r[0]] = None
            elif op in STORE_TYPES:
                base_reg = reg(re.search(r"\((\$\w+)\)", a[1]).group(1))
                off = a[1].split("(")[0]
                if field is None or regs.get(base_reg) != field:
                    return None
                v, t = value(r[0] if r[0] else None)
                lines.append(f"IG_SET({t if t and op == 'sw' else STORE_TYPES[op]}, {off}, {v})")
            elif op == "jalr":
                if regs.get(25) != ("vfn",) or regs.get(4, ("",))[0] != "orig" or regs.get(5) != ("int", 1):
                    return None
                field = ("copy", nfield)
                nfield += 1
                regs[2] = field
            elif op == "jal":
                t = a[0]
                if t == "func_002FE470":
                    regs[2] = ("base", 0)
                elif t == "metaSetFieldTypes":
                    types, count = regs[5][1], regs[6][1]
                    kinds.setdefault(types, "data")
                elif t == "func_002FDF00":
                    if regs.get(4) != ("meta",) or regs.get(5, ("",))[0] != "base":
                        return None
                    close()
                    field = ("field", nfield)
                    nfield += 1
                    lines.append(f"IG_FIELD({regs[5][1]})")
                    regs[2] = field
                elif t == "func_002FDF20":
                    close()
                    name = regs[5][1]
                    kinds.setdefault(name, "data")
                    lines.append(f"IG_FIELD_OVERRIDE({name})")
                    regs[2] = ("orig",)
                elif t == "func_002EA820":
                    regs[2] = ("index",)
                elif t == "func_002FDEA0":
                    if field is None or field[0] != "copy":
                        return None
                    close()
                    skipping = True
                elif t in FIELD_SETTERS or (field is not None and regs.get(4) == field):
                    if field is None or regs.get(4) != field:
                        return None
                    v, _ = value(5)
                    if t not in FIELD_SETTERS:
                        kinds.setdefault(t, "fieldset")
                        v = f"(s32){v}" if not isinstance(v, int) else v
                    lines.append(f"IG_CALL({t}, {v})")
                    regs[2] = None
                elif t == "metaSetFieldNames":
                    close()
                    names, a2, offs = regs[5][1], regs[6][1], regs[7][1]
                elif names is not None:  # Alchemy: one more call, with a function
                    if post is not None or regs.get(4, ("",))[0] != "sym":
                        return None
                    post = (t, regs[4][1])
                else:  # a getter: no arguments
                    regs[2] = ("ret", t)
            else:
                return None
    except (ValueError, KeyError, TypeError, IndexError, AttributeError):
        return None
    if only_overrides:
        close()
        if not isinstance(meta, str) or skipping:
            return None
        return "\n".join([f"IG_META_OVERRIDES({fn}, {meta})"] + lines + ["IG_OVERRIDES_END"]), kinds
    if not all(isinstance(x, str) for x in (meta, types, names, a2, offs)) or not isinstance(count, int):
        return None
    for s in (names, a2, offs):
        kinds.setdefault(s, "data")
    # Fields that only point an object ref at a class: the shorter IG_FIELD_REF.
    out = []
    j = 0
    while j < len(lines):
        m = re.match(r"IG_FIELD\((\d+)\)$", lines[j])
        s = re.match(r"IG_SET\(void\*, 0x38, (\w+)\(\)\)$", lines[j + 1]) if m and j + 2 < len(lines) else None
        if m and s and lines[j + 2] == "IG_FIELD_END":
            out.append(f"IG_FIELD_REF({m.group(1)}, {s.group(1)})")
            j += 3
            continue
        out.append(lines[j])
        j += 1
    end = f"IG_FIELDS_END({names}, {a2}, {offs})"
    if post:
        end = f"IG_FIELDS_END_CALL({names}, {a2}, {offs}, {post[0]}, {post[1]})"
        kinds.setdefault(post[0], "setfn")
        kinds.setdefault(post[1], "void")
    return "\n".join([f"IG_META_FIELDS({fn}, {meta}, {types}, {count})"] + out + [end]), kinds


DECL = {
    "meta": "extern igMetaObject* {};",
    "enum": "extern igMetaEnum* {};",
    "data": "extern char {}[];",
    "void": "void {}(void);",
    "getmeta": "igMetaObject* {}(void);",
    "enumget": "igMetaEnum* {}(void);",
    "vtable": "void* {}(void);",
    "inst": "igObject* {}(igMemoryPool* pool);",
    "setfn": "void* {}(void* fn);",
    "fieldset": "void {}(igMetaField* f, s32 v);",
}


def header_names():
    text = "".join(p.read_text() for p in (ROOT / "include").glob("*.h"))
    return set(re.findall(r"\b(\w+)\s*(?:\(|\[|;)", text))


def generate(src, text):
    unit = configure.unit_name(Path(src))
    sizes = struct_sizes()
    funcs = {}  # fn -> asm
    for m in INCLUDE_ASM.finditer(text):
        funcs[m.group(2)] = load_asm(unit, m.group(2))
    for m in MACRO.finditer(text):
        funcs[m.group(2)] = load_asm(unit, m.group(2))
    funcs = {k: v for k, v in funcs.items() if v}
    # retrieveVTable function -> class, from the register calls
    vtable_class = {}
    vtable_fns = set()
    for fn, f in funcs.items():
        if f["calls"][1:] == ["metaRegister"]:
            regs, _ = track_call(delay_slot_fix(f), 1)
            meta, vt = regs.get(5), regs.get(11)
            if isinstance(vt, str):
                vtable_fns.add(vt)
            _, stack = track_call(delay_slot_fix(f), 1)
            if isinstance(stack.get(8), str):
                vtable_fns.add(stack[8])
            if isinstance(meta, str) and meta.endswith("_Meta") and isinstance(vt, str):
                vtable_class[vt] = meta[:-5]
    gen = {}
    kinds = {}
    defs = {}
    for fn, f in funcs.items():
        r = recognize(fn, f, vtable_class, sizes, vtable_fns)
        if r:
            gen[fn] = r[0]
            for s, k in r[1].items():
                kinds.setdefault(s, k)
            if fn in r[1]:
                defs[fn] = r[1][fn]
    kinds.update(defs)  # a function's own definition decides its prototype
    return unit, gen, kinds, set(funcs)


def rewrite(src, text, unit, gen, kinds, skip=(), known=None):
    # macros back to INCLUDE_ASM first, so the result only depends on `gen`; macros of
    # functions without asm here (partial asm, e.g. no ELF) stay, with their prototypes.
    text = MACRO.sub(lambda m: f'INCLUDE_ASM("asm/nonmatchings/{unit}", {m.group(2)});\n'
                     if known is None or m.group(2) in known else m.group(0), text)
    old = {}
    if BEGIN in text:
        pre, rest = text.split(BEGIN, 1)
        block, post = rest.split(END, 1)
        for line in block.splitlines():
            m = re.match(r"(?:extern )?[\w*]+\s+\**(\w+)(?:\[\]|\(.*\))?;$", line.strip())
            if m and m.group(1) not in kinds:
                old[m.group(1)] = line.strip()
        text = pre.rstrip("\n") + "\n" + post.lstrip("\n")
    have = header_names() | HEADER_SYMS
    used = {s: DECL[k].format(s) for s, k in kinds.items() if s not in have}
    used.update({s: d for s, d in old.items() if s not in have})
    lines = [BEGIN, '#include "ig_meta.h"', "", 'extern "C" {']
    lines += [d for _, d in sorted(used.items())]
    lines += ["}", END, ""]
    incs = list(re.finditer(r"^#include .*\n", text, re.M))
    at = incs[-1].end() if incs else 0
    text = text[:at] + "\n" + "\n".join(lines) + text[at:].lstrip("\n")
    text = INCLUDE_ASM.sub(lambda m: gen[m.group(2)] if m.group(2) in gen and m.group(2) not in skip
                           else m.group(0), text)
    return text


def compile_and_compare(src, names):
    flags = configure.mwcc_flags(Path(src)).split()
    wibo = os.environ.get("WIBO", configure.WIBO)
    mwcc = os.environ.get("MWCC", configure.MWCC)
    with tempfile.TemporaryDirectory() as d:
        obj = Path(d) / "unit.o"
        r = subprocess.run([wibo, mwcc, *flags, "-o", str(obj), src], cwd=ROOT,
                           env={**os.environ, "MWCIncludes": "."}, capture_output=True, text=True)
        if r.returncode:
            return None, r.stdout + r.stderr
        r = subprocess.run([sys.executable, "tools/fcmp.py", str(obj)], cwd=ROOT,
                           capture_output=True, text=True)
    # Without names fcmp only lists the functions that differ (or have no address).
    bad = set(re.findall(r"^(\w+): (?:DIFF|no address)$", r.stdout, re.M))
    return {n: "DIFF" if n in bad else "MATCH" for n in names}, ""


def error_funcs(text, err):
    """Generated functions on the source lines MWCC reports errors at."""
    lines = text.splitlines()
    out = set()
    for n in re.findall(r"^#\s+(\d+):", err, re.M):
        i = int(n) - 1
        while 0 <= i < len(lines) and lines[i].startswith(("IG_FIELD", "IG_SET", "IG_CALL", "IG_OVERRIDES")):
            i -= 1  # a field line belongs to the IG_META_FIELDS above it
        m = re.match(r"IG_META_\w+\((\w+)", lines[i]) if 0 <= i < len(lines) else None
        if m:
            out.add(m.group(1))
    return out


def run(src, check, dry_run):
    path = ROOT / src
    orig = path.read_text()
    unit, gen, kinds, known = generate(src, orig)
    if dry_run:
        for fn, m in gen.items():
            print(m)
        print(f"{src}: {len(gen)} functions recognized")
        return
    if not gen:
        return
    skip = set()
    while True:
        path.write_text(rewrite(src, orig, unit, gen, kinds, skip, known))
        if not check:
            break
        status, err = compile_and_compare(src, [f for f in gen if f not in skip])
        if status is None:
            bad = error_funcs(path.read_text(), err) - skip
            if not bad:
                path.write_text(orig)
                print(f"{src}: compile failed, restored:\n{err}")
                return
            for f in sorted(bad):
                print(f"{f}: compile error, back to INCLUDE_ASM")
            skip |= bad
            continue
        bad = {f for f, s in status.items() if s != "MATCH"}
        if not bad:
            break
        for f in sorted(bad):
            print(f"{f}: {status[f]}, back to INCLUDE_ASM")
        skip |= bad
    print(f"{src}: {len(gen) - len(skip)} functions written as IG_META_* macros")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src", nargs="+")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    for src in args.src:
        run(src, args.check, args.dry_run)


if __name__ == "__main__":
    main()
