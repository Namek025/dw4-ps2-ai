#!/usr/bin/env python3
"""Write the trivial functions of a unit as C: the ones whose whole body is one fixed shape.

    jr ra; nop                          void f(void) {}
    jr ra; daddu/addiu v0, 0, N         s32 f(void) { return N; }
    lui at; jr ra; lw v0, %lo(X)(at)    igMetaObject* f(void) { return X; }   (X = *_Meta)
    sw zero, 0(a0); jr ra; daddu v0, a0 void** f(void** p) { *p = 0; return p; }
                                        (out-of-line constructor of a pointer-sized object)

Each recognized INCLUDE_ASM is replaced in place; globals the bodies use get an extern "C"
declaration. With --check the unit is compiled and every written function compared against
the rom (tools/fcmp.py, as in meta_src.py); the ones that differ go back to INCLUDE_ASM.

Usage: python3 tools/trivial_src.py src/UNIT.cpp... [--check] [--dry-run]
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import meta_src  # noqa: E402
from meta_src import INCLUDE_ASM, SYM, load_asm, reg  # noqa: E402

GEN_END = "// END generated by tools/meta_src.py"


def recognize(fn, f):
    """(C text, {global: declaration}) or None."""
    ins = f["ins"]
    ops = f["ops"]
    if ops == ["jr", "nop"]:
        return f"void {fn}(void) {{\n}}", {}
    if len(ins) == 2 and ops[0] == "jr" and reg(ins[1][1][0]) == 2:
        op, a = ins[1]
        if op == "daddu" and reg(a[1]) == 0 and reg(a[2]) == 0:
            return f"s32 {fn}(void) {{\n    return 0;\n}}", {}
        if op == "addiu" and reg(a[1]) == 0:
            return f"s32 {fn}(void) {{\n    return {int(a[2], 0)};\n}}", {}
    if ops == ["lui", "jr", "lw"] and reg(ins[2][1][0]) == 2:
        m = SYM.search(ins[2][1][1])
        if m and m.group(1).endswith("_Meta"):
            x = m.group(1)
            return f"igMetaObject* {fn}(void) {{\n    return {x};\n}}", {x: f"extern igMetaObject* {x};"}
    if ops == ["sw", "jr", "daddu"] and [reg(r) for r in ins[0][1][:1]] == [0] and \
            ins[0][1][1] == "0x0($4)" and [reg(r) for r in ins[2][1]] == [2, 4, 0]:
        return f"void** {fn}(void** p) {{\n    *p = 0;\n    return p;\n}}", {}
    return None


def rewrite(text, unit, gen, decls):
    have = meta_src.header_names()
    need = [d for x, d in sorted(decls.items())
            if x not in have and not re.search(r"\bextern\b[^;\n]*\b%s\s*(?:\[\])?;" % x, text)]
    text = INCLUDE_ASM.sub(lambda m: gen[m.group(2)] if m.group(2) in gen else m.group(0), text)
    if not need:
        return text
    if "igMetaObject" in "".join(need) and '#include "common.h"' in text:
        text = text.replace('#include "common.h"', '#include "game.h"', 1)
    # first extern "C" block of the unit itself (not the meta_src one)
    body = text.split(GEN_END, 1)[-1]
    m = re.search(r'^extern "C" \{\n', body, re.M)
    if m:
        at = len(text) - len(body) + m.end()
        return text[:at] + "\n".join(need) + "\n" + text[at:]
    if GEN_END in text:
        at = text.index(GEN_END) + len(GEN_END) + 1
    else:
        incs = list(re.finditer(r"^#include .*\n", text, re.M))
        at = incs[-1].end() if incs else 0
    block = '\nextern "C" {\n' + "\n".join(need) + "\n}\n"
    return text[:at] + block + text[at:]


def run(src, check, dry_run):
    path = ROOT / src
    orig = path.read_text()
    unit = meta_src.configure.unit_name(Path(src))
    gen, decls = {}, {}
    for m in INCLUDE_ASM.finditer(orig):
        f = load_asm(unit, m.group(2))
        r = recognize(m.group(2), f) if f else None
        if r:
            gen[m.group(2)] = r[0]
            decls.update(r[1])
    if dry_run:
        for fn, c in gen.items():
            print(c)
        print(f"{src}: {len(gen)} functions recognized")
        return
    if not gen:
        return
    while gen:
        path.write_text(rewrite(orig, unit, gen, decls))
        if not check:
            break
        status, err = meta_src.compile_and_compare(src, list(gen))
        if status is None:
            path.write_text(orig)
            print(f"{src}: compile failed, restored:\n{err}")
            return
        bad = {f for f, s in status.items() if s != "MATCH"}
        if not bad:
            break
        for f in sorted(bad):
            print(f"{f}: {status[f]}, back to INCLUDE_ASM")
            del gen[f]
    if not gen:
        path.write_text(orig)
    print(f"{src}: {len(gen)} trivial functions written")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src", nargs="+")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    for src in args.src:
        run(src, args.check, args.dry_run)


if __name__ == "__main__":
    main()
