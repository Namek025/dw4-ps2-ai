#!/usr/bin/env python3
"""Write include/meta.h: a C++ struct for every Alchemy meta class.

Input is build/meta_classes.json from tools/dump_meta.py. Each struct derives
from its parent and lays out the registered fields at their original offsets
(original names); gaps and the tail up to the instance size become padding.
Object references are plain pointers to the referenced class.

Usage: python3 tools/gen_meta_header.py [build/meta_classes.json]
"""
import json
import sys
from pathlib import Path

# field meta type -> (C type, size); None size = unknown (pad to the next field)
TYPES = {
    "igIntMetaField": ("s32", 4),
    "igUnsignedIntMetaField": ("u32", 4),
    "igEnumMetaField": ("s32", 4),
    "igBoolMetaField": ("bool", 1),
    "igCharMetaField": ("s8", 1),
    "igUnsignedCharMetaField": ("u8", 1),
    "igShortMetaField": ("s16", 2),
    "igUnsignedShortMetaField": ("u16", 2),
    "igLongMetaField": ("s64", 8),
    "igUnsignedLongMetaField": ("u64", 8),
    "igFloatMetaField": ("f32", 4),
    "igDoubleMetaField": ("f64", 8),
    "igStringMetaField": ("char*", 4),
    "igRawRefMetaField": ("void*", 4),
    "igMemoryRefMetaField": ("void*", 4),
    "igVec2fMetaField": ("igVec2f", 8),
    "igVec3fMetaField": ("igVec3f", 12),
    "igVec4fMetaField": ("igVec4f", 16),
    "igMatrix44fMetaField": ("igMatrix44f", 64),
}
# Types whose size the meta data doesn't give (arrays, embedded structs).
PADDED = ("Array", "igStructMetaField")


def cname(n):
    return n if n.isidentifier() else "_" + "".join(c if c.isalnum() else "_" for c in n)


def main():
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "build/meta_classes.json")
    classes = {c["name"]: c for c in json.loads(src.read_text()) if c["name"]}
    order, done = [], set()

    def visit(n):
        if n in done or n not in classes:
            return
        done.add(n)
        visit(classes[n]["parent"])
        order.append(n)

    for n in sorted(classes):
        visit(n)

    out = [
        "#ifndef META_H",
        "#define META_H",
        "",
        "/* Generated by tools/gen_meta_header.py from the game's Alchemy reflection",
        "   data (tools/dump_meta.py). Do not edit; field names are the original ones.",
        "   Gaps the meta data doesn't describe are padding (unkXX). */",
        "",
        '#include "common.h"',
        "",
        "typedef struct { f32 x, y; } igVec2f;",
        "typedef struct { f32 x, y, z; } igVec3f;",
        "typedef struct { f32 x, y, z, w; } igVec4f;",
        "typedef struct { f32 m[4][4]; } igMatrix44f;",
        "",
    ]
    out += [f"struct {cname(n)};" for n in order]
    out.append("")
    for n in order:
        c = classes[n]
        par = c["parent"] if c["parent"] in classes else None
        start = classes[par]["size"] if par else 0
        size = c["size"] or start
        head = f"struct {cname(n)}" + (f" : {cname(par)}" if par else "") + " {"
        body = []
        if not par:
            body.append("    void* _vtbl;  /* igObject: vtable and reference count */")
            body.append("    u32 _refCount;")
            start = 8 if size >= 8 else 0
        pos = start
        fields = sorted(c["fields"], key=lambda f: f["offset"])
        for i, f in enumerate(fields):
            off = f["offset"]
            if off < pos:
                body.append(f"    /* 0x{off:X} {f['name']}: overlaps, skipped */")
                continue
            if off > pos:
                body.append(f"    u8 unk{pos:X}[0x{off - pos:X}];")
                pos = off
            t = f["type"]
            nxt = fields[i + 1]["offset"] if i + 1 < len(fields) else size
            if t == "igObjectRefMetaField":
                ctype, fsize = (cname(f["ref"]) + "*" if f.get("ref") in classes else "igObject*"), 4
            elif t in TYPES:
                ctype, fsize = TYPES[t]
            else:
                ctype, fsize = None, nxt - off
            if ctype is None or fsize is None:
                body.append(f"    u8 {cname(f['name'])}[0x{fsize:X}];  /* {t} */")
            else:
                body.append(f"    {ctype} {cname(f['name'])};  /* 0x{off:X} */")
            pos = off + fsize
        if size > pos:
            body.append(f"    u8 unk{pos:X}[0x{size - pos:X}];")
        out.append(f"/* size 0x{size:X} */")
        out.append(head)
        out += body
        out.append("};")
        out.append("")
    out.append("#endif /* META_H */")
    Path("include/meta.h").write_text("\n".join(out) + "\n")
    print(f"{len(order)} structs written to include/meta.h")


if __name__ == "__main__":
    main()
